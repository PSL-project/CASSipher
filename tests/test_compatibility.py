"""v0.1.0 backwards compatibility; public test fixture, password is deliberately not secret."""
import tempfile
import unittest
from pathlib import Path

from cassipher import __version__
from cassipher.engine import decrypt, inspect_file, MAGIC

FIXTURE = Path(__file__).resolve().parent / 'fixtures' / 'legacy-v0.1.0.cwbox'
PASSWORD = 'published test password, do not use for real files'
CONTENT = b'CASSipher compatibility fixture generated by the original Cipher Workbench v0.1.0 code.\n'

class LegacyFormatCompatibility(unittest.TestCase):
    def test_legacy_v010_decrypts_in_cassipher(self):
        self.assertEqual(MAGIC, b'CWBOX1\r\n')
        self.assertEqual(inspect_file(FIXTURE)['version'], 1)
        with tempfile.TemporaryDirectory() as td:
            output = decrypt(FIXTURE, td, password=PASSWORD)
            self.assertEqual(Path(output['outputs'][0]).read_bytes(), CONTENT)

    def test_version(self):
        self.assertEqual(__version__, '0.1.1')
